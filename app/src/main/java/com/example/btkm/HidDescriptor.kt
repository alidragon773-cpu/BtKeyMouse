package com.example.btkm

object HidDescriptor {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2
    const val SHIFT = 0x02

    val DESCRIPTOR: ByteArray = intArrayOf(
        // Keyboard (report id 1): modifiers, reserved, 6 keys
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
        0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00,
        0xC0,
        // Mouse (report id 2): buttons, x, y, wheel
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
        0x95, 0x03, 0x75, 0x01, 0x81, 0x02,
        0x95, 0x01, 0x75, 0x05, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
        0xC0, 0xC0
    ).map { it.toByte() }.toByteArray()

    // char -> (usage, modifier)
    fun charToHid(c: Char): Pair<Int, Int>? {
        when (c) {
            in 'a'..'z' -> return (0x04 + (c - 'a')) to 0
            in 'A'..'Z' -> return (0x04 + (c - 'A')) to SHIFT
            in '1'..'9' -> return (0x1E + (c - '1')) to 0
            '0' -> return 0x27 to 0
        }
        val shiftedDigits = "!@#$%^&*("
        val i = shiftedDigits.indexOf(c)
        if (i >= 0) return (0x1E + i) to SHIFT
        if (c == ')') return 0x27 to SHIFT
        return when (c) {
            '\n' -> 0x28 to 0
            ' ' -> 0x2C to 0
            '\t' -> 0x2B to 0
            '-' -> 0x2D to 0;  '_' -> 0x2D to SHIFT
            '=' -> 0x2E to 0;  '+' -> 0x2E to SHIFT
            '[' -> 0x2F to 0;  '{' -> 0x2F to SHIFT
            ']' -> 0x30 to 0;  '}' -> 0x30 to SHIFT
            '\\' -> 0x31 to 0; '|' -> 0x31 to SHIFT
            ';' -> 0x33 to 0;  ':' -> 0x33 to SHIFT
            '\'' -> 0x34 to 0; '"' -> 0x34 to SHIFT
            '`' -> 0x35 to 0;  '~' -> 0x35 to SHIFT
            ',' -> 0x36 to 0;  '<' -> 0x36 to SHIFT
            '.' -> 0x37 to 0;  '>' -> 0x37 to SHIFT
            '/' -> 0x38 to 0;  '?' -> 0x38 to SHIFT
            else -> null
        }
    }
}
